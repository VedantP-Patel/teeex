export function isGraphicFilename(filename: string): boolean {
  return /\.(?:png|jpe?g|pdf|eps|svg|gif|webp)$/i.test(filename);
}

export function getPlaceholderGraphicBytes(filename: string): Uint8Array {
  const lower = filename.toLowerCase();
  if (lower.endsWith('.png')) return DUMMY_1X1_PNG;
  if (lower.endsWith('.pdf')) return DUMMY_1X1_PDF;
  if (lower.endsWith('.jpg') || lower.endsWith('.jpeg')) return DUMMY_1X1_JPG;
  // Default to standard PNG for unspecified or other formats
  return DUMMY_1X1_PNG;
}

/**
 * Parses all image filenames referenced in TeX code, including \includegraphics and bracketed paths.
 */
export function extractReferencedImages(texContent: string): string[] {
  const images = new Set<string>();
  const includeGraphicsRegex = /\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}/g;
  for (const match of texContent.matchAll(includeGraphicsRegex)) {
    const raw = match[1]?.trim();
    if (raw) images.add(raw);
  }
  const extRegex = /\{([a-zA-Z0-9_./-]+\.(?:jpe?g|png|gif|svg|eps|pdf|webp))\}/gi;
  for (const match of texContent.matchAll(extRegex)) {
    const raw = match[1]?.trim();
    if (raw) images.add(raw);
  }
  return Array.from(images);
}
